#!/usr/bin/env python3
"""
Build letter-land/words.js from data/words.json (the word list per level) and data/emoji.json (a picture for each word).

  python3 letter-land/tools/make_words.py

Edit data/words.json to change levels or words, then run this and rebuild.
Real pictures: put them in img/ (the `image` field of each word) and set window.LETTERLAND_IMAGES = true before game.js loads.
"""
import json, os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
data = json.load(open(os.path.join(root, 'data', 'words.json'), encoding='utf-8'))
emoji = json.load(open(os.path.join(root, 'data', 'emoji.json'), encoding='utf-8'))
missing = [w['id'] for w in data['words'] if w['id'] not in emoji]
if missing:
    print('no emoji for:', ', '.join(missing), file=sys.stderr)
for w in data['words']:
    w['emoji'] = emoji.get(w['id'], '❓')
out = {'levels': data['levels'], 'words': data['words']}
with open(os.path.join(root, 'words.js'), 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/make_words.py from data/words.json + data/emoji.json. Do not edit by hand. */\n')
    f.write('window.LetterWords = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('words.js:', len(data['words']), 'words,', len(data['levels']), 'levels')
